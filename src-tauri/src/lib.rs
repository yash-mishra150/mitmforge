use serde::{Deserialize, Serialize};
use specta::Type;

pub mod client;
mod commands;
pub mod proxy;
pub mod system_proxy;

/// Single error type crossing the IPC boundary; the UI switches on `kind`.
#[derive(Clone, Debug, thiserror::Error, Serialize, Deserialize, Type)]
pub enum ProxyError {
    #[error("proxy is already running")]
    AlreadyRunning,
    #[error("io: {message}")]
    Io { message: String },
    #[error("{message}")]
    Internal { message: String },
}

/// Name of the single backend → UI event. Payload: [`proxy::ProxyEvent`].
pub const PROXY_EVENT: &str = "proxy://event";

/// Also used by `export_bindings` (tests) to regenerate `src/bindings.ts`.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    commands::builder()
}

pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n/* eslint-disable */\n// Generated by tauri-specta. Do not edit; run `npm run gen:bindings`.",
            ),
            "../src/bindings.ts",
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    let typed_invoke = builder.invoke_handler();
    let app = tauri::Builder::default()
        // Must be the first plugin: a second launch focuses this instance
        // instead of spawning a competitor for port 8080.
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            use tauri::Manager;
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_opener::init())
        .manage(proxy::BodyStore::shared())
        .invoke_handler(typed_invoke)
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application");

    app.run(|_app, event| {
        if matches!(
            event,
            tauri::RunEvent::ExitRequested { .. } | tauri::RunEvent::Exit
        ) {
            // Stop the engine and put the system proxy back the way we found
            // it BEFORE the runtime teardown (which would otherwise wait on
            // the engine task forever and get killed, skipping the restore).
            commands::proxy::shutdown_engine();
            system_proxy::restore_on_exit();
        }
    });
}
